/*
 * Write data/chapters.js: one import per chapter module that exists (data/chNN.js).
 *   node scripts/gen-chapters.mjs
 */
import { readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../data/', import.meta.url);
const files = readdirSync(dir).filter(f => /^ch\d\d\.js$/.test(f)).sort();
const lines = files.map(f => `import { chapter as c${f.slice(2, 4)} } from './${f}';`);
const out = `/* Generated by scripts/gen-chapters.mjs — every chapter module in data/. */\n${lines.join('\n')}\n\nexport const CHAPTERS = [${files.map(f => `c${f.slice(2, 4)}`).join(', ')}];\n`;
writeFileSync(new URL('chapters.js', dir), out);
console.log(`data/chapters.js: ${files.length} chapters`);
